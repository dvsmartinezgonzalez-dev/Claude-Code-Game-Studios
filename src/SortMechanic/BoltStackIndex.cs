using UnityEngine;

namespace BoltSort.SortMechanic
{
    /// <summary>
    /// Attached to every BoltStack collider. Exposes the flat column index used by
    /// <see cref="SortMechanic"/> to identify which stack was tapped via
    /// <c>Physics2D.OverlapPoint</c> (ADR-0007 tap pipeline).
    ///
    /// Flat index convention (must match GSM interface layout):
    ///   0 .. (colorCount-1)                      = color stacks
    ///   colorCount .. (colorCount+tempCount-1)    = temp slots
    /// </summary>
    public class BoltStackIndex : MonoBehaviour
    {
        /// <summary>Flat column index assigned in the scene or generated by the level builder.</summary>
        [field: SerializeField]
        public int Index { get; private set; }
    }
}
